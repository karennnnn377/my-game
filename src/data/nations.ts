/** cc → flag emoji (regional indicators) */
export function flagOf(cc: string | undefined): string {
  if (!cc) return "";
  const up = cc.toUpperCase();
  if (up.length !== 2 || !/^[A-Z]{2}$/.test(up)) return "";
  return String.fromCodePoint(...[...up].map((c) => 127397 + c.charCodeAt(0)));
}

export function countryName(cc: string | undefined, lang: "en" | "fa" | "ar"): string {
  if (!cc) return "";
  const c = COUNTRIES[cc];
  if (!c) return cc;
  return lang === "fa" ? c[1] : lang === "ar" ? c[2] : c[0];
}
